const hiddenSpecMd = `# AWSアーキテクチャ設計課題

## 小規模チーム向けファイル共有サービスを設計せよ

### 背景

あなたは、従業員20名ほどの会社で利用する、社内向けファイル共有サービスを開発することになりました。

社員は、業務で使うPDFや画像を同じ共有領域に置き、認証済みの社員であれば一覧から見つけてダウンロードできる状態にしたいと考えています。個人用フォルダの集合ではなく、部署の資料置き場としての利用を想定しています。

現在は利用者数が少ないため、運用負荷と月額コストをできるだけ抑えたいと考えています。

以下の要件を満たすAWSアーキテクチャを設計し、AWS CDKで実装してください。

---

## 1. 機能要件

システムは、以下の機能を提供します。

### ファイルの登録

認証済みの利用者は、以下の形式のファイルを共有領域へ登録できます。

* PDF
* JPEG
* PNG

1ファイルあたりの最大サイズは10MBです。

ファイルの登録に成功した場合、システムはファイルIDを返してください。

ファイルのアップロード方法やAPIの形式は自由に設計できます。

### ファイル一覧の取得

認証済みの利用者は、共有領域に登録されたファイルの一覧を確認できます。自分が登録したファイルに限定する必要はありません。

一覧には、最低限以下の情報を含めてください。

* ファイルID
* ファイル名
* ファイルサイズ
* 登録日時
* 登録した利用者を識別できる情報

一度に大量のファイルを返さないように、取得件数を制限できる構成にしてください。

### ファイルのダウンロード

認証済みの利用者は、ファイルIDを指定して、共有領域のファイルをダウンロードできます。

未認証の利用者や、インターネット上の不特定多数がファイルを取得できてはなりません。

ファイルの保存場所を、誰でもアクセスできる状態でインターネットへ公開してはなりません。

### ファイルの削除

ファイルを削除できるのは、次のいずれかです。

* そのファイルを登録した本人
* 管理者ロールを持つ利用者

一般利用者は、他人が登録したファイルを削除できてはなりません。

削除後のファイルを、通常の操作で再び取得できてはなりません。

---

## 2. 利用者の認証

システムを利用するには認証が必要です。

システムは、少なくとも以下を識別できる必要があります。

* どの利用者がリクエストを送信したか
* どの利用者が各ファイルを登録したか
* その利用者が管理者ロールを持つかどうか

認証方法とロールの表現方法は自由に設計できます。

利用者のパスワードや認証情報を、AWS CDKコードやアプリケーションコードへ直接記述してはいけません。

---

## 3. 想定利用規模

初期段階では、以下の利用規模を想定しています。

* 利用者数は20名
* 1日あたり合計100回程度のAPIリクエスト
* 1日あたり合計20ファイル程度の登録
* ファイルの平均サイズは3MB
* 共有領域全体で最大20,000ファイル程度
* 将来的に利用者数が100名程度になる可能性がある

利用されていない時間にも、高額な固定費が発生する構成は避けてください。

---

## 4. 性能

通常時は、以下を目標とします。

* ファイル一覧の取得は1秒以内に応答する
* ファイルのダウンロード開始までを3秒以内とする
* 複数の利用者が同時に操作しても、特定の利用者の処理によってシステム全体が長時間停止しないこと

厳密な負荷試験は必要ありません。

採用した構成が、想定利用規模に対して妥当である理由を説明してください。

---

## 5. セキュリティ

以下を満たしてください。

* ファイルの保存場所を一般公開しないこと
* 社外の不特定多数がファイルを取得・削除できないこと
* 認証済みの社員であれば共有領域のファイルを閲覧・ダウンロードできること
* 削除は登録者本人または管理者に限定すること
* 保存されたファイルとファイル情報を暗号化すること
* 各AWSリソースに与える権限を必要な範囲に限定すること
* APIへ認証なしでアクセスできないようにすること
* 認証情報や機密情報をコードへ直接記述しないこと

ファイル名には、個人名や顧客名などが含まれる可能性があります。ログへ不要なファイル名や認証情報を出力しないようにしてください。

---

## 6. データ管理

登録されたファイルは、登録から90日後に自動的に削除してください。

ファイル一覧を管理するための情報についても、適切な保存期間を設計してください。

ファイル本体の削除と、ファイル一覧に表示する情報の削除が一致するようにしてください。

AWS CDKのスタックを削除した場合に、登録済みファイルを残すか、一緒に削除するかは自由に決められます。判断した理由を説明してください。

---

## 7. ログと監視

運用者が、少なくとも以下を確認できるようにしてください。

* APIでエラーが発生しているか
* ファイルの登録やダウンロードで失敗が増えていないか
* アプリケーションの実行中に例外が発生していないか
* 想定より多くのリクエストが発生していないか

障害調査に必要なログを記録し、ログの保存期間を明示してください。

一定数以上のエラーが発生した場合に、運用者が検知できる仕組みを用意してください。

通知先のメールアドレスなどは、固定値をコードに直接記述しなくても構いません。

---

## 8. コスト

初期段階では利用量が少ないため、次の点を重視してください。

* 利用量に応じて費用が増減する構成
* 常時稼働するサーバーを必要以上に持たない構成
* 運用担当者が日常的にサーバー管理をしなくてもよい構成
* 想定規模に対して過剰な冗長化を避けた構成

正確な月額料金の計算は必須ではありません。

どのAWSリソースに主な費用が発生するかを説明してください。
`;

